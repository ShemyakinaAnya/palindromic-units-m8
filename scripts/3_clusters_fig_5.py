# Fig. 5D

df = pd.read_csv('all_h_clusters.tsv', sep='\t', index_col=False)

overlap_values = sorted(df['overlap'].unique())
type_categories = sorted(df['type'].unique())
fig, axes = plt.subplots(1, 2, figsize=(14, 6), sharey=True)
color_palette = sns.color_palette("colorblind", n_colors=len(type_categories))
for i, overlap_val in enumerate(overlap_values):
    subset = df[df['overlap'] == overlap_val]

    sns.countplot(
        data=subset,
        x='n_of_h',
        hue='type',
        dodge=0.2,
        ax=axes[i],
        palette=color_palette,
        order=sorted(df['n_of_h'].unique())  # Ensure consistent x-axis order
    )

    axes[i].tick_params(axis='both', labelsize=16)
    axes[i].set_title(f'Overlapping: {overlap_val}', fontsize=16)
    axes[i].set_xlabel('Number of PUs in a cluster', fontsize=16)

    if i == 0:
        axes[i].set_ylabel('Number of clusters', fontsize=16)
    else:
        axes[i].set_ylabel('')  # Remove y-label for second plot

    axes[i].legend_.remove()

    for container in axes[i].containers:
        axes[i].bar_label(container, fontsize=14)

plt.legend(title='Position relative to CDSs', bbox_to_anchor=(1.02, 1), loc='upper left', title_fontsize=16,
           fontsize=16)
plt.tight_layout()
plt.savefig('Fig_5D')
plt.show()

