# extract fasta sequences from filtered tsv
def extract_fasta(input_tsv, output_fasta):
    with open(input_tsv, 'r') as tsv_file, open(output_fasta, 'w') as fasta_file:
        tsv_file.readline()
        while True:
            line = tsv_file.readline().split('\t')
            if not line or len(line) < 15:
                break
            fasta_file.write(f'>{line[0]}_{line[1]} ({line[3]}..{line[4]})\n')
            fasta_file.write(f'{line[-1]}')


