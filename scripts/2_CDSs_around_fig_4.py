def prep_df_for_fig_4B(output_name, struc_file, cds_in_file):
    with open(output_name, 'w') as out_file, open(struc_file, "r") as in_struc_file, open(cds_in_file,
                                                                                          "r") as in_cds_file:
        in_struc_file.readline()
        in_cds_file.readline()
        out_file.write('\t'.join(
            ['h_name', 'stem_len', 'dist', '3_5_end']) + '\n')
        while True:
            line = in_cds_file.readline().strip().split('\t')
            if not line[0]:
                break
            stem_len = in_struc_file.readline().strip().split('\t')[6]
            if line[11] != 'inside' and line[19] != 'inside' and int(line[10]) < 3000 and int(line[18]) < 3000:
                out_line_start = [line[3], stem_len]

                up_dist = line[10]
                up_dir = line[6]
                up_out_line = []
                up_out_line.extend(out_line_start)
                up_out_line.append(up_dist)
                if up_dir == '+':
                    up_out_line.append("stop codon")
                else:
                    up_out_line.append("start codon")
                out_file.write('\t'.join(up_out_line) + '\n')

                dw_dist = line[18]
                dw_dir = line[14]
                dw_out_line = []
                dw_out_line.extend(out_line_start)
                dw_out_line.append(dw_dist)
                if dw_dir == '+':
                    dw_out_line.append("start codon")
                else:
                    dw_out_line.append("stop codon")
                out_file.write('\t'.join(dw_out_line) + '\n')


