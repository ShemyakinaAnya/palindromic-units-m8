# predict mRNA secondary structures of hairpins with mfold
def mfold_output_parsing(path_to_ct_file):
    with open(path_to_ct_file) as file:
        lines = file.readlines()
        dG = lines[0].split(' ')[3]
        pairs = []
        for i in range(1, len(lines)):
            line = lines[i].split()
            if line[4] != '0':
                pairs.append([int(line[0]), int(line[4])])
    del line
    del lines

    counting_stem = False
    stem_size = 0
    loop_size = 0
    bulges = ''
    for i in range(len(pairs)):
        # going upwards alongside the stem, searching the loop
        if not counting_stem:
            if i != len(pairs) - 1:  # not last pair
                if pairs[i + 1][0] - pairs[i][0] > 1:  # loop?
                    if pairs[i][0] == pairs[i + 1][1] and pairs[i][1] == pairs[i + 1][0]:  # yes, loop
                        loop_size = pairs[i][1] - pairs[i][0] - 1
                        stem_size = 1
                        counting_stem = True
            else:
                break
        else:
            # going downwards alongside the stem, counting the stem length, searching for bulges
            if i != len(pairs) - 1:  # still not last pair
                left_dist = pairs[i][1] - pairs[i + 1][1]
                right_dist = pairs[i + 1][0] - pairs[i][0]
                if right_dist > 1 or left_dist > 1:
                    if right_dist == left_dist:
                        bulges += '_c' + str(right_dist - 1)
                    elif right_dist > 1:
                        bulges += '_r' + str(right_dist - 1)
                    else:
                        bulges += '_l' + str(left_dist - 1)
                stem_size += 1
            else:  # stem ended
                counting_stem = False

    return [stem_size, loop_size, dG, bulges]


def mfolding(mfold_output_dir, input_fasta, output_name):
    os.makedirs(f"./{mfold_output_dir}", exist_ok=True)
    with open(output_name, 'w') as output_file:
        output_file.write('name\tmolecule\tstart\tstop\tGC\tdG\tstem_len\tloop_size\tbulges\n')
        for record in SeqIO.parse(input_fasta, "fasta"):
            dir_name = f"./{mfold_output_dir}/{record.name}"
            os.makedirs(dir_name, exist_ok=True)
            with open(f'{dir_name}/{record.name}.fasta', 'w') as f:
                des_line = record.description.split(' ')
                h_name = des_line[0].split('_')[0]
                molecule = '_'.join(des_line[0].split('_')[1:3])
                coords = des_line[2].split('..')
                start = coords[0][1:]
                stop = coords[1][:-1]
                gc_content = round(((record.seq.count('G') + record.seq.count('C')) / len(record.seq)) * 100, 1)
                f.write('>' + str(record.name) + '\n')
                f.write(str(record.seq))
            print('\n\n\n')
            print(f'mfold on {record.name}')
            print('\n')
            subprocess.run([mfold_path, 'SEQ=' + f'{record.name}.fasta'], cwd=dir_name + '/')
            stem_size, loop_size, dG, bulges = mfold_output_parsing(f'{dir_name}/{record.name}_1.ct')
            output_file.write('\t'.join(
                [h_name, molecule, start, stop, str(gc_content), dG, str(stem_size), str(loop_size), bulges, '\n']))
            shutil.move(f'{dir_name}/{record.name}_1.ps', f'./{mfold_output_dir}/{record.name}_1.ps')
            shutil.rmtree(dir_name)


