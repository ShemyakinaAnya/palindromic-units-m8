# correct distances between hairpins and closest CDSs found by bedtools
def correct_distances(output_name, cds_in_file, close_max_dist):
    with open(output_name, 'w') as out_file, open(cds_in_file, "r") as in_file:
        in_file.readline()
        out_file.write('\t'.join(
            ['mol', 'h_start', 'h_stop', 'h_name', 'up_gene_ID', 'up_prot_ID', 'up_direct', 'up_start', 'up_stop',
             'up_prod', 'up_dist', 'up_dist_type', 'down_gene_ID', 'down_prot_ID', 'down_direct', 'down_start',
             'down_stop', 'down_prod', 'down_dist', 'down_dist_type']) + '\n')
        while True:
            line = in_file.readline().split('\t')
            if not line[0]:
                break
            h_start = int(line[1])
            h_stop = int(line[2])
            # up_start = int(line[7])
            up_stop = int(line[8])
            dw_start = int(line[14])
            # dw_stop = int(line[15])

            up_type = ''
            up_dist = ''
            if h_start > up_stop:  # far or close
                up_dist = h_start - up_stop
                if up_dist < close_max_dist:
                    up_type = 'close'
                else:
                    up_type = 'far'
            elif h_start <= up_stop:  # overlap or inside
                if h_stop > up_stop:
                    up_type = 'overlap'
                    up_dist = h_start - up_stop
                else:
                    up_type = 'inside'

            dw_type = ''
            dw_dist = ''
            if dw_start > h_stop:  # far or close
                dw_dist = dw_start - h_stop - 1
                if dw_dist < close_max_dist:
                    dw_type = 'close'
                else:
                    dw_type = 'far'
            elif dw_start <= h_stop:  # overlap or inside
                if h_start < dw_start:
                    dw_type = 'overlap'
                    dw_dist = dw_start - h_stop - 1
                else:
                    dw_type = 'inside'

            line[10] = str(up_dist)
            line[17] = str(dw_dist)
            line.insert(11, up_type)
            line.append(dw_type)
            out_file.write('\t'.join(line) + '\n')


