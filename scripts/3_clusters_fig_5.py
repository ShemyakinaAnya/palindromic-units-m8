# CLUSTERING HAIRPINS

def find_h_clusters(mfold_file, cds_file, out_file, dist_between):
    with open(mfold_file, 'r') as mfold_input, open(cds_file, 'r') as cds_input, open(out_file, 'w') as output:
        output.write('\t'.join(
            ['n_of_h', 'h_names', 'h_stem_lens', 'h_stem_len_av', 'dist_between_h', 'dist_between_h_av',
             'cluster_start', 'cluster_stop',
             'up_name', 'up_dist', 'up_utr', 'dw_name', 'dw_dist', 'dw_utr', 'av_dist', 'overlap', 'type']) + '\n')
        mfold_input.readline()
        cds_input.readline()
        two_name = ''
        two_start = 0
        two_stop = 0
        two_stem_len = 0
        inside_cluster = False
        h_cluster = {'h_names': [], 'h_stem_lens': [], 'h_stem_len_av': '', 'dist_between_h': [],
                     'dist_between_h_av': ''}
        type = ''
        while True:
            line = mfold_input.readline().split('\t')
            if not line[0]:
                break
            one_start = two_start
            one_stop = two_stop
            one_name = two_name
            one_stem_len = two_stem_len
            two_start = int(line[2])
            two_stop = int(line[3])
            two_name = line[0]
            two_stem_len = line[6]
            if two_start - one_stop < dist_between:
                if one_name not in h_cluster['h_names']:
                    inside_cluster = True
                    h_cluster['h_names'].append(one_name)
                    h_cluster['h_stem_lens'].append(one_stem_len)
                    cluster_start = one_start
                h_cluster['h_names'].append(two_name)
                h_cluster['h_stem_lens'].append(two_stem_len)
                h_cluster['dist_between_h'].append(str(two_start - one_stop - 1))
            else:
                if inside_cluster:
                    inside_cluster = False
                    cluster_end = one_stop
                    h_stem_lens = [int(x) for x in h_cluster['h_stem_lens']]
                    h_cluster['h_stem_len_av'] = str(sum(h_stem_lens) / len(h_stem_lens))
                    h_dists_between = [int(x) for x in h_cluster['dist_between_h']]
                    h_cluster['dist_between_h_av'] = str(sum(h_dists_between) / len(h_dists_between))
                    overlap = str(any(num < 0 for num in h_dists_between))

                    while True:
                        cds_line = cds_input.readline().split('\t')
                        if h_cluster['h_names'][0] == cds_line[3]:
                            first_h_up_type = cds_line[11]
                            first_h_dw_type = cds_line[19].strip()
                            up_name = cds_line[4]
                            up_dist = cds_line[10]
                            if cds_line[6] == '+':
                                up_utr = "'3"
                            else:
                                up_utr = "'5"
                        elif h_cluster['h_names'][-1] == cds_line[3]:
                            last_h_up_type = cds_line[11]
                            last_h_dw_type = cds_line[19].strip()
                            dw_name = cds_line[12]
                            dw_dist = cds_line[18]
                            if cds_line[14] == '+':
                                dw_utr = "'5"
                            else:
                                dw_utr = "'3"
                            break
                    av_dist = ''
                    if up_dist and dw_dist:
                        av_dist = str((int(up_dist) + int(dw_dist)) / 2)

                    if 'inside' in [first_h_up_type, first_h_dw_type] and 'inside' in [last_h_up_type, last_h_dw_type]:
                        type = 'inside'
                    else:
                        type = 'outside'

                    output.write('\t'.join(
                        [str(len(h_cluster['h_names'])), ';'.join(h_cluster['h_names']),
                         ';'.join(h_cluster['h_stem_lens']),
                         h_cluster['h_stem_len_av'], ';'.join(h_cluster['dist_between_h']),
                         h_cluster['dist_between_h_av'],
                         str(cluster_start), str(cluster_end),
                         up_name, up_dist, up_utr, dw_name, dw_dist, dw_utr, av_dist, overlap, type]) + '\n')
                    h_cluster = {'h_names': [], 'h_stem_lens': [], 'dist_between_h': []}


find_h_clusters(f'{path_to_in_1}chr_mfold_straight.tsv', f'{path_to_in_2}chr_CDS_around_h_cor_dist.tsv',
                'chr_h_clusters.tsv', 15)
find_h_clusters(f'{path_to_in_1}pl_mfold_straight.tsv', f'{path_to_in_2}pl_CDS_around_h_cor_dist.tsv',
                'pl_h_clusters.tsv', 15)

# merge result files
command = "{ cat chr_h_clusters.tsv; tail -n +2 pl_h_clusters.tsv; } > all_h_clusters.tsv"
subprocess.run(command, shell=True, check=True)

