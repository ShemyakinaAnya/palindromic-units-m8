# find CDSs around haipins with bedtools
# (dics for manual correction of cases when both closest CDSs are from the same side)
def find_CDSs_around(genome_gff, h_bed, human_dic, output_name):
    with open(output_name, 'w') as out_file:
        out_file.write('\t'.join(
            ['mol', 'h_start', 'h_stop', 'h_name', 'up_gene_ID', 'up_prot_ID', 'up_direct', 'up_start', 'up_stop',
             'up_prod', 'up_dist', 'down_gene_ID', 'down_prot_ID', 'down_direct', 'down_start', 'down_stop',
             'down_prod', 'down_dist', '\n']))
        command = [bedtools_path, 'closest', '-d', '-D', 'ref', '-k', '2', '-t', 'first', '-a',
                   h_bed, '-b', genome_gff]
        with open('bedtools_output.tsv', "w") as bedtools_output:
            subprocess.run(command, stdout=bedtools_output, check=True)
        with open('bedtools_output.tsv', "r") as bed_output:
            content = bed_output.readlines()
            it = iter(content)
            for _ in range(len(content) // 2):
                one_gene = next(it).strip().split('\t')
                two_gene = next(it).strip().split('\t')
                output_line = one_gene[0:4]
                h_coords = one_gene[1:3]
                closest_coords = one_gene[9:11]
                closest_direct = one_gene[12]
                closest_dist = one_gene[-1]
                further_coords = two_gene[9:11]
                further_direct = two_gene[12]
                further_dist = two_gene[-1]

                # parse closest gene
                for t in one_gene[14].split(';'):
                    if 'ID=' in t:
                        closest_prot_ID = t.split('=')[1].split('-')[1]
                    if 'product=' in t:
                        closest_product = t.split('=')[1]
                    if 'Parent=' in t:
                        closest_gene_ID = t.split('=')[1].split('-')[1]

                # ask for second closest gene if bedtools's variant is behind the closest one
                if int(closest_coords[0]) < int(further_coords[0]):  # closest CDS is upstream
                    up_coords = closest_coords[:]
                    dw_coords = further_coords[:]
                else:  # closest CDS is downstream
                    up_coords = further_coords[:]
                    dw_coords = closest_coords[:]

                if not (int(h_coords[0]) > int(up_coords[0]) and int(h_coords[1]) < int(
                        dw_coords[1])):  # hairpin not between two genes!!
                    if one_gene[3] in human_dic.keys():
                        correct_further_gene_ID = human_dic[one_gene[3]]
                    else:
                        correct_further_gene_ID = input(
                            f'Correct second gene for hairpin {one_gene[3]} closest to {closest_gene_ID} - ')
                    with open(genome_gff, 'r') as gff:
                        while True:
                            gff_line = gff.readline().strip()
                            if not gff_line:
                                raise ValueError(f"No {correct_further_gene_ID} in genome")
                            if correct_further_gene_ID in gff_line:
                                gff_line_ = gff_line.strip().split('\t')
                                further_coords = gff_line_[3:5]
                                further_direct = gff_line_[6]
                                further_gene_ID = correct_further_gene_ID
                                if closest_coords[0] < further_coords[0]:
                                    further_dist = str(int(further_coords[0]) - int(h_coords[1]))
                                else:
                                    further_dist = str(int(h_coords[0]) - int(further_coords[1]))
                                for t in gff_line_[8].split(';'):
                                    if 'ID=' in t:
                                        further_prot_ID = t.split('=')[1].split('-')[1]
                                    if 'product=' in t:
                                        further_product = t.split('=')[1]
                                break
                else:  # second CDS is correct

                    for t in two_gene[14].split(';'):
                        if 'ID' in t:
                            further_prot_ID = t.split('=')[1].split('-')[1]
                        if 'product' in t:
                            further_product = t.split('=')[1]
                        if 'Parent' in t:
                            further_gene_ID = t.split('=')[1].split('-')[1]

                if int(closest_coords[0]) < int(further_coords[0]):  # closest CDS is upstream
                    output_line.extend([closest_gene_ID, closest_prot_ID, closest_direct]
                                       + closest_coords + [closest_product, closest_dist])
                    output_line.extend([further_gene_ID, further_prot_ID, further_direct]
                                       + further_coords + [further_product, further_dist])
                else:  # closest CDS is downstream
                    output_line.extend([further_gene_ID, further_prot_ID, further_direct]
                                       + further_coords + [further_product, further_dist])
                    output_line.extend([closest_gene_ID, closest_prot_ID, closest_direct]
                                       + closest_coords + [closest_product, closest_dist])

                out_file.write('\t'.join(output_line) + '\n')


