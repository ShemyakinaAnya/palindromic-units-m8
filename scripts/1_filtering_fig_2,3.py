# filter nested PUs
def filter_nested_h(in_file, out_file):
    with open(in_file, 'r') as input, open(out_file, 'w') as output:
        output.write(input.readline())
        two_start = 0
        two_stop = 0
        two_name = ''
        prev_nested = False
        while True:
            line = input.readline()
            line_ = line.split('\t')
            if not line_[0]:
                break
            if not prev_nested:
                one_start = two_start
                one_stop = two_stop
                one_name = two_name
            two_start = int(line_[3])
            two_stop = int(line_[4])
            two_name = line_[0]
            if two_stop - (two_stop - two_start) / 2 == one_stop - (one_stop - one_start) / 2:
                print(f'{two_name} nested in {one_name}')
                prev_nested = True
            else:
                output.write(line)
                prev_nested = False


