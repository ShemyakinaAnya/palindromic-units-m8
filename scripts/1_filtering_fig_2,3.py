def plot_h_pos(h_positions, genome_length, tick_length=0.03, linewid=0.1, tick_interval_kb=100):
    angles = [pos / genome_length * 2 * np.pi for pos in h_positions]
    fig, ax = plt.subplots(subplot_kw={'projection': 'polar'})
    theta = np.linspace(0, 2 * np.pi, 1000)
    ax.plot(theta, [1] * 1000, color='black', linewidth=2)

    # Calculate tick positions
    genome_kb = genome_length / 1000
    tick_positions_kb = np.arange(0, genome_kb + tick_interval_kb / 2, tick_interval_kb)
    tick_positions_bp = tick_positions_kb * 1000
    tick_angles = [pos / genome_length * 2 * np.pi for pos in tick_positions_bp]

    valid_ticks = [(angle, kb) for angle, kb in zip(tick_angles, tick_positions_kb)
                   if kb * 1000 <= genome_length]

    for angle, kb in valid_ticks:
        ax.plot([angle, angle], [1, 1.05], color='black', linewidth=1)
        rotation_deg = -np.rad2deg(angle)
        rotation = rotation_deg + 90
        rotation = rotation % 360
        if 90 < rotation < 270:
            rotation += 180
        label = f'{kb:.0f}'
        ax.text(angle, 1.125, label,
                ha='center', va='center',
                rotation=rotation,
                rotation_mode='anchor',
                fontsize=12)

    # Draw h positions
    for angle in angles:
        ax.plot([angle, angle], [1 - tick_length, 1 + tick_length / 2],
                color='red', linewidth=linewid, solid_capstyle='round', alpha=0.8)

    ax.set_ylim(0.5, 1.3)
    ax.set_yticks([])
    ax.set_xticks([])
    ax.spines['polar'].set_visible(False)
    ax.grid(False)

    ax.set_theta_zero_location('N')
    ax.set_theta_direction(-1)

    plt.tight_layout()
    return fig, ax


def prepartion_for_plot(gff, mfold_file, in_linewid, in_tick_interval_kb, fig_name):
    with open(gff, 'r') as gff_file:
        while True:
            gff_line = gff_file.readline()
            if '##sequence-region' in gff_line:
                genome_length = int(gff_line.split(' ')[-1])
                break
    h_coords = []
    with open(mfold_file, 'r') as in_file:
        in_file.readline()
        while True:
            line = in_file.readline().strip().split('\t')
            if not line[0]:
                break
            h_coords.append(round(((int(line[2]) + int(line[3])) / 2)))

    fig, ax = plot_h_pos(
        h_positions=h_coords,
        genome_length=genome_length,
        tick_length=0.05,
        linewid=in_linewid,
        tick_interval_kb=in_tick_interval_kb)
    plt.savefig(fig_name)
    plt.show()


